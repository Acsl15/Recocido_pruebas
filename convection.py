def convection_heat_flux(
    *,
    h_eff: float,
    T_g: float,
    T_surface: float
) -> float:
    '''
    Calculate convective heat flux from gas to steel.

    Args:
        h_eff: effective heat-transfer coefficient in W/(m2 K).
        T_g: gas temperature in K.
        T_surface: steel surface temperature in K.

    Returns:
        Heat flux in W/m2.

    Raises:
        ValueError if h_eff is negative or temperatures are invalid.
    '''

    if h_eff < 0:
        raise ValueError(
            "h_eff cannot be negative."
        )

    if T_g <= 0:
        raise ValueError(
            "T_g must be positive."
        )

    if T_surface <= 0:
        raise ValueError(
            "T_surface must be positive."
        )

    return h_eff * (
        T_g - T_surface
    )


def convection_power(
    *,
    h_eff: float,
    area: float,
    T_g: float,
    T_surface: float
) -> float:
    '''
    Calculate total convective heat transfer.

    Args:
        h_eff: effective heat-transfer coefficient in W/(m2 K).
        area: heat-transfer area in m2.
        T_g: gas temperature in K.
        T_surface: steel surface temperature in K.

    Returns:
        Heat-transfer rate in W.

    Raises:
        ValueError if h_eff or area is negative or temperatures are invalid.
    '''

    if area < 0:
        raise ValueError(
            "area cannot be negative."
        )

    q_flux = convection_heat_flux(
        h_eff=h_eff,
        T_g=T_g,
        T_surface=T_surface
    )

    return q_flux * area