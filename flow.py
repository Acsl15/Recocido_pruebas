import numpy as np


def flow_distribution_coefficients(
    *,
    n_coils: int,
    zeta: float
) -> np.ndarray:
    '''
    Calculate flow distribution coefficients for all convector plates.

    The expression is the generalized form of the distribution relation
    used in the four-coil model from the paper.

    Args:
        n_coils: number of coils in the stack.
        zeta: flow attenuation coefficient.

    Returns:
        Array containing the flow distribution coefficients from the
        bottom plate to the top plate.

    Raises:
        ValueError if n_coils is less than 2, zeta is not positive,
        or any coefficient is greater than or equal to 1.
    '''

    if n_coils < 2:
        raise ValueError(
            "n_coils must be at least 2."
        )

    if zeta <= 0:
        raise ValueError(
            "zeta must be positive."
        )

    j = np.arange(1, n_coils)

    fd = (
        zeta ** (n_coils - 1 - j)
        / (2.0 + n_coils)
    )

    if np.any(fd >= 1.0):
        raise ValueError(
            "Every flow distribution coefficient must be less than 1."
        )

    return fd


def channel_flows(
    *,
    q_total: float,
    fd: np.ndarray
) -> tuple[np.ndarray, np.ndarray, float]:
    '''
    Calculate gas flow through plates, side channels, and top channel.

    Args:
        q_total: total volumetric gas flow in m3/s.
        fd: flow distribution coefficients from bottom to top.

    Returns:
        Tuple containing:

        q_plates:
            flow through each convector plate in m3/s.

        q_sides:
            gas flow along the side surfaces of each coil in m3/s.

        q_top:
            flow entering the top channel in m3/s.

    Raises:
        ValueError if q_total is not positive or any coefficient is
        outside the interval (0, 1).
    '''

    if q_total <= 0:
        raise ValueError(
            "q_total must be positive."
        )

    fd = np.asarray(fd, dtype=float)

    if np.any(fd <= 0) or np.any(fd >= 1):
        raise ValueError(
            "Every flow distribution coefficient must be between 0 and 1."
        )

    n_plates = len(fd)
    n_coils = n_plates + 1

    q_plates = np.zeros(n_plates)
    q_sides = np.zeros(n_coils)

    remaining = q_total

    for j in range(n_plates):

        # Flow reaching this coil
        q_sides[j] = remaining

        # Flow leaving through the plate
        q_plates[j] = remaining * fd[j]

        # Flow continuing upward
        remaining *= (1.0 - fd[j])

    # Flow reaching final coil
    q_sides[-1] = remaining

    # Remaining flow exits through the top
    q_top = remaining

    return q_plates, q_sides, q_top


def surface_flows(
    *,
    q_total: float,
    n_coils: int,
    zeta: float
) -> list[dict[str, float]]:
    '''
    Calculate gas flow assigned to every surface of every coil.

    Args:
        q_total: total volumetric gas flow in m3/s.
        n_coils: number of coils in the stack.
        zeta: flow attenuation coefficient.

    Returns:
        List containing one dictionary per coil. Each dictionary
        contains the flow along the inner, outer, bottom, and top
        surfaces in m3/s.

    Raises:
        ValueError if n_coils is less than 2 or q_total or zeta is
        not positive.
    '''

    fd = flow_distribution_coefficients(
        n_coils=n_coils,
        zeta=zeta
    )

    q_plates, q_sides, q_top = channel_flows(
        q_total=q_total,
        fd=fd
    )

    surfaces = []

    for i in range(n_coils):

        # Bottom surface
        if i == 0:
            bottom = 0.0
        else:
            bottom = q_plates[i - 1]

        # Top surface
        if i < n_coils - 1:
            top = q_plates[i]
        else:
            top = q_top

        surfaces.append(
            {
                "inner": q_sides[i],
                "outer": q_sides[i],
                "bottom": bottom,
                "top": top
            }
        )

    return surfaces


def actual_flow_rate(
    *,
    q_normal: float,
    T_g: float,
    pressure: float = 101325.0
) -> float:
    '''
    Convert normal volumetric flow to actual volumetric flow.

    Args:
        q_normal: volumetric flow at normal conditions in m3/s.
        T_g: gas temperature in K.
        pressure: gas pressure in Pa.

    Returns:
        Actual volumetric flow in m3/s.

    Raises:
        ValueError if q_normal, T_g, or pressure is not positive.
    '''

    if q_normal <= 0:
        raise ValueError(
            "q_normal must be positive."
        )

    if T_g <= 0:
        raise ValueError(
            "T_g must be positive."
        )

    if pressure <= 0:
        raise ValueError(
            "pressure must be positive."
        )

    return (
        q_normal
        * (T_g / 273.15)
        * (101325.0 / pressure)
    )